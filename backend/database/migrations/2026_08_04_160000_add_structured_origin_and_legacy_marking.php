/**
 * Two changes that turn traceability from something DERIVED into something QUERYABLE.
 *
 * ── 1. Structured origin on every amount ────────────────────────────────────────────────────────────
 * Until now, "which document backs this line?" was answered by reverse-looking-up four tables at read
