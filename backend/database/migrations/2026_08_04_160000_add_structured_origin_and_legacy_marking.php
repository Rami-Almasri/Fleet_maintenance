 * of it, and `cost:trace-audit` re-derives rather than trusting the cache, so a stale value is caught
 * rather than believed.
 *
 * ── 2. Legacy marking, without faking history ───────────────────────────────────────────────────────
 * 173,934 AED of existing ticket cost has no document and never will — it was recorded before the
 * documents existed. Inventing invoices for it would be far worse than admitting it, so instead every
 * cost that predates this rollout is stamped `cost_legacy_at`. That separates two things which look
 * identical in a total but are completely different in meaning:
 *
 *     LEGACY UNVERIFIED — recorded before the rules existed. Known, bounded, and shrinking as it is
 *                         migrated. Not anyone's fault.
 *     UNVERIFIED        — recorded AFTER the rules existed, with no document. Should be impossible now
